import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import { test } from "node:test";

const url = process.env.CANDIDATE_TEST_DATABASE_URL;
test("batch repair preserves staff edits and refuses shared images", { skip: !url }, async () => {
  assert.equal(new URL(url).pathname, "/candidate_copy_test");
  const require = createRequire(import.meta.url);
  const { Client } = createRequire(require.resolve("@payloadcms/db-postgres"))("pg");
  const db = new Client({ connectionString: url });
  await db.connect();
  let dir;
  try {
    const existing = await db.query("SELECT count(*)::integer AS count FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','S')");
    assert.equal(existing.rows[0].count, 0, "Refusing a nonempty database");
    await db.query(`CREATE TABLE media (id integer PRIMARY KEY, updated_at timestamptz DEFAULT now());
      CREATE TABLE products (id integer PRIMARY KEY, slug text, source_url text, review_status text, claims_verified boolean, image_id integer REFERENCES media(id), updated_at timestamptz DEFAULT now());
      CREATE TABLE products_locales (_parent_id integer, _locale text, name text, intro text);
      CREATE TABLE media_locales (_parent_id integer REFERENCES media(id), _locale text, alt text);
      CREATE TABLE articles (id integer PRIMARY KEY, image_id integer REFERENCES media(id))`);
    const inventory = JSON.parse(await fs.readFile("src/data/official-site-product-candidates.json", "utf8"));
    const merged = new Set([754923,754921,754926,754931,754932,754918,754919]);
    const candidates = inventory.products.filter(c => !merged.has(Number(c.sourceUrl.match(/\/(\d+)\.html$/)[1])));
    assert.equal(candidates.length, 21);
    for (const [index, c] of candidates.entries()) {
      const id = index + 1, sourceId = c.sourceUrl.match(/\/(\d+)\.html$/)[1];
      const oldName = `KOMU product · ${c.name}`;
      const oldIntro = `The official KOMU product center lists ${c.name}. Model, packaging, technical values and claims remain subject to formal review.`;
      await db.query("INSERT INTO media (id) VALUES ($1)",[id]);
      await db.query("INSERT INTO products (id,slug,source_url,review_status,claims_verified,image_id) VALUES ($1,$2,$3,'owner-review',false,$1)",[id,`official-${sourceId}`,c.sourceUrl]);
      await db.query("INSERT INTO products_locales VALUES ($1,'en',$2,$3),($1,'zh',$4,$4)",[id,oldName,index === 0 ? "Staff edit" : oldIntro,c.name]);
      await db.query("INSERT INTO media_locales VALUES ($1,'en',$2),($1,'zh',$3)",[id,JSON.stringify({en:oldName,zh:c.name}),c.name]);
    }
    dir = await fs.mkdtemp(path.join(os.tmpdir(), "candidate-batch-test-"));
    const backup = path.join(dir,"fixture.dump");
    await fs.writeFile(backup,"isolated fixture only");
    const run = journal => spawnSync(process.execPath,["scripts/repair-official-candidate-copy.mjs"],{cwd:process.cwd(),encoding:"utf8",env:{...process.env,DATABASE_URL:url,OFFICIAL_CANDIDATE_COPY_ISOLATED_TEST:"YES",OFFICIAL_CANDIDATE_COPY_CONFIRM:"YES",OFFICIAL_CANDIDATE_COPY_EDIT_FREEZE:"CONFIRMED",OFFICIAL_CANDIDATE_COPY_BACKUP:backup,OFFICIAL_CANDIDATE_COPY_JOURNAL:journal}});
    await db.query("INSERT INTO articles VALUES (1,1)");
    const rejected = run(path.join(dir,"conflict.json"));
    assert.notEqual(rejected.status,0);
    assert.equal((await db.query("SELECT count(*)::integer AS n FROM products_locales WHERE _locale='en' AND name LIKE 'KOMU product · %'")).rows[0].n,21);
    await db.query("DELETE FROM articles");
    const blockedJournal = path.join(dir,"exists.json");
    await fs.writeFile(blockedJournal,"existing journal");
    const blocked = run(blockedJournal);
    assert.notEqual(blocked.status,0);
    assert.equal((await db.query("SELECT count(*)::integer AS n FROM products_locales WHERE _locale='en' AND name LIKE 'KOMU product · %'")).rows[0].n,21);
    assert.equal(await fs.readFile(blockedJournal,"utf8"),"existing journal");
    const markerCollisionJournal = path.join(dir,"marker-collision.json");
    await fs.writeFile(`${markerCollisionJournal}.committed`,"existing marker");
    const markerCollision = run(markerCollisionJournal);
    assert.notEqual(markerCollision.status,0);
    assert.equal((await db.query("SELECT count(*)::integer AS n FROM products_locales WHERE _locale='en' AND name LIKE 'KOMU product · %'")).rows[0].n,21);
    assert.equal(await fs.readFile(`${markerCollisionJournal}.committed`,"utf8"),"existing marker");
    assert.equal(await fs.stat(markerCollisionJournal).catch(() => null),null,"A marker collision must be rejected before writing a journal or mutating data");
    const journal = path.join(dir,"applied.json");
    const applied = run(journal);
    assert.equal(applied.status,0,applied.stderr);
    const report = JSON.parse(applied.stdout);
    assert.equal(report.changed,21);
    assert.equal((await db.query("SELECT intro FROM products_locales WHERE _parent_id=1 AND _locale='en'")).rows[0].intro,"Staff edit");
    assert.equal((await db.query("SELECT count(*)::integer AS n FROM products_locales WHERE _locale='zh'")).rows[0].n,21);
    const saved = JSON.parse(await fs.readFile(journal,"utf8"));
    assert.equal(saved.changes.length,21);
    assert.equal((await fs.stat(`${journal}.committed`)).isFile(),true);
    const repairedNames = (await db.query("SELECT _parent_id,name FROM products_locales WHERE _locale='en' ORDER BY _parent_id")).rows;
    const rollback = () => spawnSync(process.execPath,["scripts/rollback-official-candidate-copy.mjs"],{cwd:process.cwd(),encoding:"utf8",env:{...process.env,DATABASE_URL:url,OFFICIAL_CANDIDATE_COPY_ISOLATED_TEST:"YES",OFFICIAL_CANDIDATE_COPY_EDIT_FREEZE:"CONFIRMED",OFFICIAL_CANDIDATE_ROLLBACK_CONFIRM:"YES",OFFICIAL_CANDIDATE_COPY_JOURNAL:journal}});
    const originalJournal = await fs.readFile(journal);
    await fs.appendFile(journal," ");
    const tampered = rollback();
    assert.notEqual(tampered.status,0);
    assert.match(tampered.stderr,/Invalid or uncommitted journal/);
    await fs.writeFile(journal,originalJournal);
    await db.query("UPDATE products_locales SET intro='Later staff edit' WHERE _parent_id=21 AND _locale='en'");
    const conflict = rollback();
    assert.notEqual(conflict.status,0);
    assert.match(conflict.stderr,/changed since repair/);
    assert.deepEqual((await db.query("SELECT _parent_id,name FROM products_locales WHERE _locale='en' ORDER BY _parent_id")).rows,repairedNames);
    const last = saved.changes.find(item => item.id === 21);
    await db.query("UPDATE products_locales SET intro=$1 WHERE _parent_id=21 AND _locale='en'",[last.text.after.intro]);
    const restored = rollback();
    assert.equal(restored.status,0,restored.stderr);
    assert.equal((await db.query("SELECT count(*)::integer AS n FROM products_locales WHERE _locale='en' AND name LIKE 'KOMU product · %'")).rows[0].n,21);
    assert.equal((await db.query("SELECT intro FROM products_locales WHERE _parent_id=1 AND _locale='en'")).rows[0].intro,"Staff edit");
    const repeated = rollback();
    assert.notEqual(repeated.status,0);
    assert.match(repeated.stderr,/changed since repair/);
  } finally {
    await db.end();
    if (dir) await fs.rm(dir,{recursive:true,force:true});
  }
});
